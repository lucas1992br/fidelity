<?php

namespace Database\Factories;

use App\Enums\EntryStatus as EntryStatusEnum;
use App\Enums\EntryType as EntryTypeEnum;
use App\Enums\PaymentMethod as PaymentMethodEnum;
use App\Models\FinancialCategory;
use App\Models\FinancialEntry;
use App\Models\Payment;
use App\Models\User;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * Entries default to a pending manual expense. The entry type always follows
 * the category's type, as enforced by the composite foreign key.
 *
 * @extends Factory<FinancialEntry>
 */
class FinancialEntryFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        $faker = fake('pt_BR');

        return [
            'financial_category_id' => FinancialCategory::factory()->expense(),
            'entry_type_id' => fn (array $attributes): int => FinancialCategory::findOrFail((int) $attributes['financial_category_id'])->entry_type_id,
            'description' => rtrim($faker->sentence(3), '.'),
            'amount' => $faker->randomFloat(2, 10, 2000),
            'due_date' => $faker->dateTimeBetween('-1 month', '+1 month')->format('Y-m-d'),
            'entry_status_id' => fn (): int => EntryStatusEnum::Pending->id(),
            'paid_at' => null,
            'payment_method_id' => null,
            'payment_id' => null,
            'supplier_or_payer' => $faker->company(),
            'notes' => null,
            'user_id' => User::factory(),
        ];
    }

    public function income(): static
    {
        return $this->state(fn (array $attributes) => [
            'financial_category_id' => FinancialCategory::factory()->income(),
        ]);
    }

    public function expense(): static
    {
        return $this->state(fn (array $attributes) => [
            'financial_category_id' => FinancialCategory::factory()->expense(),
        ]);
    }

    public function pending(): static
    {
        return $this->state(fn (array $attributes) => [
            'entry_status_id' => EntryStatusEnum::Pending->id(),
            'paid_at' => null,
            'payment_method_id' => null,
        ]);
    }

    public function paid(): static
    {
        return $this->state(fn (array $attributes) => [
            'entry_status_id' => EntryStatusEnum::Paid->id(),
            'paid_at' => $attributes['due_date'],
            'payment_method_id' => $attributes['payment_method_id'] ?? PaymentMethodEnum::Pix->id(),
        ]);
    }

    public function cancelled(): static
    {
        return $this->state(fn (array $attributes) => [
            'entry_status_id' => EntryStatusEnum::Cancelled->id(),
            'paid_at' => null,
        ]);
    }

    /**
     * Income generated by a payment, in the "Mensalidades" system category,
     * mirroring the payment's date, amount and method.
     */
    public function automatic(?Payment $payment = null): static
    {
        return $this->state(function (array $attributes) use ($payment): array {
            $payment ??= Payment::factory()->create();

            return [
                'financial_category_id' => FinancialCategory::monthlyFees()->id,
                'entry_type_id' => EntryTypeEnum::Income->id(),
                'description' => 'Mensalidade — recibo '.$payment->refresh()->receipt_number,
                'amount' => $payment->amount,
                'due_date' => $payment->paid_at->toDateString(),
                'entry_status_id' => EntryStatusEnum::Paid->id(),
                'paid_at' => $payment->paid_at->toDateString(),
                'payment_method_id' => $payment->payment_method_id,
                'payment_id' => $payment->id,
                'installment_number' => 1,
                'supplier_or_payer' => null,
                'user_id' => $payment->user_id,
            ];
        });
    }
}
