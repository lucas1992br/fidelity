<?php

namespace App\Models;

use App\Exceptions\PhysicalDeleteNotAllowed;
use Database\Factories\PaymentFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Support\Carbon;
use Spatie\Activitylog\Models\Concerns\LogsActivity;
use Spatie\Activitylog\Support\LogOptions;

/**
 * Payment of an invoice. The receipt number comes from the database sequence,
 * so it is never filled by the application: call refresh() after create().
 *
 * @property int $id
 * @property int $invoice_id
 * @property int $receipt_number
 * @property Carbon $paid_at
 * @property string $amount
 * @property int $payment_method_id
 * @property string|null $notes
 * @property int $user_id
 * @property Carbon|null $refunded_at
 * @property int|null $refunded_by_user_id
 * @property string|null $refund_reason
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
class Payment extends Model
{
    /** @use HasFactory<PaymentFactory> */
    use HasFactory, LogsActivity;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'invoice_id',
        'paid_at',
        'amount',
        'payment_method_id',
        'notes',
        'user_id',
        'refunded_at',
        'refunded_by_user_id',
        'refund_reason',
    ];

    /**
     * Payments are never deleted; a mistaken payment is refunded (US-9.4).
     */
    protected static function booted(): void
    {
        static::deleting(function (self $payment): never {
            throw PhysicalDeleteNotAllowed::for($payment);
        });
    }

    /**
     * Audit changes to the fillable attributes in the "billing" log; the causer
     * is the authenticated user (none when run by the scheduled routines).
     */
    public function getActivitylogOptions(): LogOptions
    {
        return LogOptions::defaults()
            ->useLogName('billing')
            ->logFillable()
            ->logOnlyDirty()
            ->dontLogEmptyChanges();
    }

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'receipt_number' => 'integer',
            'paid_at' => 'date',
            'amount' => 'decimal:2',
            'refunded_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<Invoice, $this>
     */
    public function invoice(): BelongsTo
    {
        return $this->belongsTo(Invoice::class);
    }

    /**
     * @return BelongsTo<PaymentMethod, $this>
     */
    public function method(): BelongsTo
    {
        return $this->belongsTo(PaymentMethod::class, 'payment_method_id');
    }

    /**
     * User who registered the payment.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function refundedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'refunded_by_user_id');
    }

    /**
     * Automatic income entry generated by the payment.
     *
     * @return HasOne<FinancialEntry, $this>
     */
    public function financialEntry(): HasOne
    {
        return $this->hasOne(FinancialEntry::class);
    }

    public function isRefunded(): bool
    {
        return $this->refunded_at !== null;
    }
}
