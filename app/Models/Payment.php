<?php

namespace App\Models;

use App\Enums\PaymentMethod as PaymentMethodEnum;
use App\Exceptions\PhysicalDeleteNotAllowed;
use Carbon\CarbonInterface;
use Database\Factories\PaymentFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;
use Spatie\Activitylog\Models\Concerns\LogsActivity;
use Spatie\Activitylog\Support\LogOptions;

/**
 * Payment of an invoice. The receipt number comes from the database sequence,
 * so it is never filled by the application: call refresh() after create().
 *
 * @property int $id
 * @property int $invoice_id
 * @property int $receipt_number
 * @property Carbon $paid_at
 * @property string $amount
 * @property int $months
 * @property int $payment_method_id
 * @property int $installments
 * @property string|null $notes
 * @property int $user_id
 * @property Carbon|null $refunded_at
 * @property int|null $refunded_by_user_id
 * @property string|null $refund_reason
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
class Payment extends Model
{
    /**
     * Most installments a card or boleto payment can be split into.
     */
    public const int MaxInstallments = 12;

    /**
     * Most consecutive months one payment can cover (a year of plan).
     */
    public const int MaxMonths = 12;

    /** @use HasFactory<PaymentFactory> */
    use HasFactory, LogsActivity;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'invoice_id',
        'paid_at',
        'amount',
        'months',
        'payment_method_id',
        'installments',
        'notes',
        'user_id',
        'refunded_at',
        'refunded_by_user_id',
        'refund_reason',
    ];

    /**
     * Payments are never deleted; a mistaken payment is refunded (US-9.4).
     */
    protected static function booted(): void
    {
        static::deleting(function (self $payment): never {
            throw PhysicalDeleteNotAllowed::for($payment);
        });
    }

    /**
     * Audit changes to the fillable attributes in the "billing" log; the causer
     * is the authenticated user (none when run by the scheduled routines).
     */
    public function getActivitylogOptions(): LogOptions
    {
        return LogOptions::defaults()
            ->useLogName('billing')
            ->logFillable()
            ->logOnlyDirty()
            ->dontLogEmptyChanges();
    }

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'receipt_number' => 'integer',
            'months' => 'integer',
            'installments' => 'integer',
            'paid_at' => 'date',
            'amount' => 'decimal:2',
            'refunded_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<Invoice, $this>
     */
    public function invoice(): BelongsTo
    {
        return $this->belongsTo(Invoice::class);
    }

    /**
     * Every invoice covered by the payment, the first one included.
     *
     * @return BelongsToMany<Invoice, $this>
     */
    public function invoices(): BelongsToMany
    {
        return $this->belongsToMany(Invoice::class)->using(InvoicePayment::class)->withTimestamps()->orderBy('reference_month');
    }

    /**
     * @return BelongsTo<PaymentMethod, $this>
     */
    public function method(): BelongsTo
    {
        return $this->belongsTo(PaymentMethod::class, 'payment_method_id');
    }

    /**
     * User who registered the payment.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function refundedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'refunded_by_user_id');
    }

    /**
     * Automatic income entries generated by the payment, one per installment.
     *
     * @return HasMany<FinancialEntry, $this>
     */
    public function financialEntries(): HasMany
    {
        return $this->hasMany(FinancialEntry::class)->orderBy('installment_number');
    }

    public function isInstallment(): bool
    {
        return $this->installments > 1;
    }

    /**
     * Covered reference months, e.g. "10/2026" or "10/2026 a 09/2027"; needs the invoice.
     */
    public function referencePeriod(): string
    {
        return self::formatPeriod($this->invoice->reference_month, $this->months);
    }

    /**
     * Label of `$months` reference months starting at `$first`.
     */
    public static function formatPeriod(CarbonInterface $first, int $months): string
    {
        if ($months === 1) {
            return $first->format('m/Y');
        }

        return $first->format('m/Y').' a '.$first->copy()->addMonthsNoOverflow($months - 1)->format('m/Y');
    }

    /**
     * Method label with the installments, e.g. "Cartão em 3x".
     */
    public function methodLabel(): string
    {
        $label = PaymentMethodEnum::fromId($this->payment_method_id)->label();

        return $this->isInstallment() ? "{$label} em {$this->installments}x" : $label;
    }

    public function isRefunded(): bool
    {
        return $this->refunded_at !== null;
    }
}
