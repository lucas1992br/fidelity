<?php

namespace App\Policies;

use App\Models\FinancialEntry;
use App\Models\User;

class FinancialEntryPolicy
{
    /**
     * Entries, payables, receivables and cash flow.
     */
    public function viewAny(User $user): bool
    {
        return $user->can('finance.view');
    }

    /**
     * Create a manual entry.
     */
    public function create(User $user): bool
    {
        return $user->can('finance.manage');
    }

    /**
     * Mark the entry as paid or received.
     */
    public function settle(User $user, FinancialEntry $entry): bool
    {
        return $user->can('finance.manage');
    }

    /**
     * Edit a manual entry; entries generated by payments are read-only.
     */
    public function update(User $user, FinancialEntry $entry): bool
    {
        return $user->can('finance.manage') && ! $entry->isAutomatic();
    }

    /**
     * Delete a manual entry; entries generated by payments are kept.
     */
    public function delete(User $user, FinancialEntry $entry): bool
    {
        return $user->can('finance.manage') && ! $entry->isAutomatic();
    }
}
